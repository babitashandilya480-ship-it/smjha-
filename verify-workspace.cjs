const {chromium}=require('playwright');
const fs=require('fs');
(async()=>{
 const browser=await chromium.launch({channel:'msedge',headless:true});
 const page=await browser.newPage({viewport:{width:1440,height:1000}});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto('http://127.0.0.1:5173');
 await page.getByRole('heading',{name:'Sign in',exact:true}).waitFor();
 await page.screenshot({path:'../../artifacts/workspace-signin.png',fullPage:true});
 await page.getByRole('button',{name:'Create an account',exact:true}).click();
 await page.getByLabel('Username',{exact:true}).fill('qa_workspace_'+Date.now());
 await page.getByLabel('Password',{exact:true}).fill('qa-local-workspace-1234');
 await page.getByRole('button',{name:'Create account',exact:true}).click();
 await page.getByRole('button',{name:'Send message',exact:true}).waitFor();
 await page.locator('.chat-top small').filter({hasText:'qwen3'}).waitFor();
 await page.screenshot({path:'../../artifacts/workspace-desktop.png',fullPage:true});
 const overflow=[];
 for(const width of [320,360,768,1440,1920]){
  await page.setViewportSize({width,height:1000});
  overflow.push({width,overflow:await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth)});
 }
 await page.setViewportSize({width:390,height:844});
 await page.screenshot({path:'../../artifacts/workspace-mobile.png',fullPage:true});
 await page.setViewportSize({width:1440,height:1000});
 await page.getByRole('button',{name:/Models & modes/}).click();
 await page.locator('.model-grid article').nth(2).waitFor();
 await page.screenshot({path:'../../artifacts/workspace-models.png',fullPage:true});
 await page.getByRole('button',{name:/Document library/}).click();
 await page.getByRole('button',{name:'Add your supplied evaluation guide',exact:true}).click();
 await page.getByRole('heading',{name:'LLM Testing and Evaluation',exact:true}).waitFor();
 await page.screenshot({path:'../../artifacts/workspace-library.png',fullPage:true});
 await page.getByRole('button',{name:'Ask about this',exact:true}).click();
 await page.getByLabel('Your message',{exact:true}).fill('According to the PDF, what is accuracy? Answer in one sentence with a page citation.');
 const started=Date.now();
 await page.getByRole('button',{name:'Send message',exact:true}).click();
 await page.locator('.chat-message.assistant').first().waitFor({timeout:90000});
 const firstTextMs=Date.now()-started;
 await page.getByRole('status').filter({hasText:/Response saved|budget|failed|timed out/}).waitFor({timeout:90000});
 const status=await page.getByRole('status').textContent();
 await page.screenshot({path:'../../artifacts/workspace-answer.png',fullPage:true});
 const answer=await page.locator('.chat-message.assistant').first().innerText();
 const sources=await page.locator('.chat-sources').count();
 const report={overflow,errors,firstTextMs,totalMs:Date.now()-started,status,answer,sources};
 fs.writeFileSync('../../artifacts/workspace-verification.json',JSON.stringify(report,null,2));
 console.log(JSON.stringify(report,null,2));
 await page.request.delete('http://127.0.0.1:5173/api/v1/account',{headers:{'X-Samjha-Local':'1'}});
 await browser.close();
 if(errors.length||overflow.some(x=>x.overflow)||!sources||status!=='Response saved.')process.exitCode=1;
})().catch(e=>{console.error(e);process.exit(1)});
